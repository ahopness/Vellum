		<section class="space-y-3">
			<h2 class="font-serif text-xl font-medium text-[#18181b]">
				1. Princípio da Minimização e Privacidade por Design (Privacy by Design)
			</h2>
			<p>
				Nossa arquitetura foi intencionalmente projetada para coletar e armazenar o <strong>mínimo estritamente necessário</strong> de dados pessoais para cumprir a finalidade de validação de presença acadêmica e profissional.
			</p>
			<div class="p-4 border-l-2 border-[#18181b] bg-white my-4 text-sm text-[#3f3f46]">
				<strong>Importante para Participantes:</strong> O seu <strong>CPF NÃO é armazenado</strong> nos servidores ou bancos de dados da plataforma. Ele é processado única e exclusivamente de forma temporária na memória do navegador do seu dispositivo (celular ou computador) para desenhar o texto do certificado que você baixa imediatamente.
			</div>
		</section>

		<hr class="border-t border-[#e4e4e7]" />

		<!-- Seção 2 -->
		<section class="space-y-6">
			<h2 class="font-serif text-xl font-medium text-[#18181b]">
				2. Dados Pessoais Tratados e Finalidades
			</h2>

			<div class="space-y-3">
				<h3 class="font-sans text-sm font-semibold uppercase tracking-wider text-[#71717a]">
					2.1. Administradores (Organizadores do Evento)
				</h3>
				<ul class="space-y-2 list-disc list-inside text-sm text-[#3f3f46]">
					<li><strong>Nome Completo:</strong> Identificação como organizador e emissor responsável do evento perante a instituição.</li>
					<li><strong>E-mail:</strong> Envio de links de acesso seguro (<em>Magic Link</em>) e contato de suporte.</li>
					<li><strong>CPF:</strong> Validação cadastral e responsabilidade pela emissão de certificados oficiais.</li>
				</ul>
			</div>

			<div class="space-y-3">
				<h3 class="font-sans text-sm font-semibold uppercase tracking-wider text-[#71717a]">
					2.2. Participantes (Alunos e Convidados)
				</h3>
				<ul class="space-y-2 list-disc list-inside text-sm text-[#3f3f46]">
					<li><strong>Nome Completo:</strong> Registro nominal na lista de presença do evento e preenchimento do certificado.</li>
					<li><strong>E-mail:</strong> Identificador único para evitar presenças duplicadas no mesmo evento.</li>
					<li><strong>Data e Hora:</strong> Comprovação temporal do momento em que a presença foi registrada.</li>
					<li><strong>CPF:</strong> <em>Não armazenado.</em> Processado estritamente em memória local para gerar o arquivo baixado.</li>
				</ul>
			</div>
		</section>

		<hr class="border-t border-[#e4e4e7]" />

		<!-- Seção 3 -->
		<section class="space-y-3">
			<h2 class="font-serif text-xl font-medium text-[#18181b]">
				3. Segurança e Prevenção a Fraudes
			</h2>
			<p>Adotamos medidas técnicas adequadas para garantir a segurança dos dados:</p>
			<ol class="space-y-2 list-decimal list-inside text-sm text-[#3f3f46]">
				<li><strong>Comunicação Criptografada:</strong> Tráfego sob protocolo HTTPS com TLS forçado.</li>
				<li><strong>Magic Links Seguros:</strong> Links de acesso de uso único válidos por 15 minutos via e-mail.</li>
				<li><strong>Janela Temporal de Presença:</strong> O credenciamento é restrito ao horário do evento (±15 min de tolerância).</li>
				<li><strong>Sanitização de Planilhas:</strong> Prevenção contra injeção de fórmulas CSV.</li>
			</ol>
		</section>

		<hr class="border-t border-[#e4e4e7]" />


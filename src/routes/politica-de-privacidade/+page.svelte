				4. Direitos do Titular de Dados (Art. 18 da LGPD)
			</h2>
			<p class="text-sm">
				Você pode confirmar a existência de tratamento, solicitar cópia dos seus registros de presença ou solicitar a eliminação dos seus dados entrando em contato direto com o organizador do seu evento ou com o suporte.
			</p>
